  @override
  void initState() {
    super.initState();
    _model = createModel(context, () => HomeDashModel());

    // On page load action.
    SchedulerBinding.instance.addPostFrameCallback((_) async {
      if (RootPageContext.isInactiveRootPage(context)) {
        return;
      }
      if (currentUserDocument?.householdId == null) {
        context.goNamed(
          OnboardingWidget.routeName,
          extra: <String, dynamic>{
            kTransitionInfoKey: TransitionInfo(
              hasTransition: true,
              transitionType: PageTransitionType.fade,
              duration: Duration(milliseconds: 0),
            ),
          },
        );
      } else {
        // Resetiramo (damo na 0) vse števce za bilanco
        _model.youOwe = 0.0;
        _model.owedToYou = 0.0;
        _model.balance = 0.0;
        _model.bills = await queryBillsRecordOnce(
          queryBuilder: (billsRecord) => billsRecord.where(
            'householdRef',
            isEqualTo: currentUserDocument?.householdId,
          ),
          limit: 100,
        );
        for (int loop1Index = 0;
            loop1Index < _model.bills!.length;
            loop1Index++) {
          final currentLoop1Item = _model.bills![loop1Index];
          _model.billItems = await queryBillItemsRecordOnce(
            queryBuilder: (billItemsRecord) => billItemsRecord.where(
              'billRef',
              isEqualTo: currentLoop1Item.reference,
            ),
            limit: 100,
          );
          for (int loop2Index = 0;
              loop2Index < _model.billItems!.length;
              loop2Index++) {
            final currentLoop2Item = _model.billItems![loop2Index];
            if (currentLoop1Item.paidBy == currentUserReference) {
              if (currentLoop2Item.participants
                  .contains(currentUserReference)) {
                // Dolžno nam je znesek na osebo * št. oseb - 1 (mene se ne šteje)
                _model.owedToYou = _model.owedToYou +
                    (currentLoop2Item.amountPerPerson *
                        (currentLoop2Item.participants.length - 1));
              } else {
                // Dolžno nam je znesek na osebo * št. oseb
                _model.owedToYou = _model.owedToYou +
                    (currentLoop2Item.amountPerPerson *
                        currentLoop2Item.participants.length);
              }
            } else {
              if (currentLoop2Item.participants
                  .contains(currentUserReference)) {
                _model.youOwe =
                    _model.youOwe + currentLoop2Item.amountPerPerson;
              }
            }
          }
        }
        _model.balance = _model.owedToYou - _model.youOwe;
        safeSetState(() {});
      }
    });

    animationsMap.addAll({
      'containerOnActionTriggerAnimation': AnimationInfo(
        trigger: AnimationTrigger.onActionTrigger,
        applyInitialState: true,
        effectsBuilder: () => [
          MoveEffect(
            curve: Curves.easeInOut,
            delay: 0.0.ms,
            duration: 300.0.ms,
            begin: Offset(-40.0, 0.0),
            end: Offset(0.0, 0.0),
          ),
        ],
      ),
    });
    setupAnimations(
      animationsMap.values.where((anim) =>
          anim.trigger == AnimationTrigger.onActionTrigger ||
          !anim.applyInitialState),
      this,
    );
  }

